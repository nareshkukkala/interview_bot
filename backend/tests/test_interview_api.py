def error_of(response):
    body = response.json()
    assert set(body) == {"error"}
    assert set(body["error"]) == {"code", "message", "details"}
    assert TEST_KEY not in response.text  # credentials never appear in any response
    return body["error"]


def evaluation_requests(gemini):
    return [r for r in gemini.requests if "technical_accuracy" in r["body"]["generationConfig"]["responseSchema"]["properties"]]


def summary_requests(gemini):
    return [r for r in gemini.requests if "summary" in r["body"]["generationConfig"]["responseSchema"]["properties"]]


def question_requests(gemini):
    return [r for r in gemini.requests if "questions" in r["body"]["generationConfig"]["responseSchema"]["properties"]]


