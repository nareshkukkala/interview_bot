def test_concurrent_duplicate_evaluations_make_a_single_ai_request(gemini):
    """Double clicks and retries must not pay for (or race on) the same evaluation twice."""
    store.clear()
    gemini.script.extend([None, slow(0.4)])  # start answers at once; the first evaluation is slow

    async def scenario():
        transport = httpx.ASGITransport(app=app)
        async with httpx.AsyncClient(transport=transport, base_url="http://test") as http:
            started = await http.post("/api/interviews/start", json=CONFIG)
            session_id = started.json()["session_id"]
            await http.post(f"/api/interviews/{session_id}/submit-answer", json={"question_number": 1, "answer": GOOD_ANSWER})
            return await asyncio.gather(
                *[http.post(f"/api/interviews/{session_id}/evaluate", json={"question_number": 1}) for _ in range(4)]
            )

    responses = asyncio.run(scenario())
    assert [r.status_code for r in responses] == [200] * 4
    assert len({json.dumps(r.json(), sort_keys=True) for r in responses}) == 1  # all got the same stored evaluation
    assert len(evaluation_requests(gemini)) == 1
    store.clear()


