def test_submit_answer_validation(client, interview):
    session_id, _ = interview
    cases = [
        ({"question_number": 1}, "An answer is required"), ({"question_number": 1, "answer": ""}, "An answer is required"),
        ({"question_number": 1, "answer": "        "}, "An answer is required"), ({"question_number": 1, "answer": "too short"}, "at least 10"),
        ({"question_number": 1, "answer": "x" * 2001}, "2,000"), ({"question_number": 0, "answer": GOOD_ANSWER}, None), ({"answer": GOOD_ANSWER}, None),
    ]
    for payload, message in cases:
        response = client.post(f"/api/interviews/{session_id}/submit-answer", json=payload)
        assert response.status_code == 422, payload
        error = error_of(response)
        assert error["code"] == "VALIDATION_ERROR"
        if message:
            assert message in " ".join(d["message"] for d in error["details"])
    assert submit(client, session_id, 1).json()["progress"]["answered"] == 1  # nothing was stored by the rejected requests


