def test_concurrent_results_requests_make_one_summary_request(gemini):
    store.clear()
    gemini.script.extend([None] + [None] * 5 + [slow(0.4)])  # start, 5 evaluations, then a slow summary

    async def scenario():
        transport = httpx.ASGITransport(app=app)
        async with httpx.AsyncClient(transport=transport, base_url="http://test") as http:
            session_id = (await http.post("/api/interviews/start", json=CONFIG)).json()["session_id"]
            for number in range(1, 6):
                await http.post(f"/api/interviews/{session_id}/submit-answer", json={"question_number": number, "answer": GOOD_ANSWER})
                await http.post(f"/api/interviews/{session_id}/evaluate", json={"question_number": number})
            return await asyncio.gather(*[http.get(f"/api/interviews/{session_id}/results") for _ in range(4)])

    responses = asyncio.run(scenario())
    assert [r.status_code for r in responses] == [200] * 4
    assert len({json.dumps(r.json(), sort_keys=True) for r in responses}) == 1
    assert len(summary_requests(gemini)) == 1
    store.clear()


