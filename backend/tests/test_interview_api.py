def test_full_interview_scores_and_report(client, interview, gemini):
    session_id, start = interview
    submit(client, session_id, 1, answer="EXCELLENT answer with plenty of correct detail and an example.")
    submit(client, session_id, 2, skipped=True)
    submit(client, session_id, 3, answer="POOR answer that misses the point entirely and is vague.")
    submit(client, session_id, 4)
    submit(client, session_id, 5)
    evals = {n: evaluate(client, session_id, n).json() for n in (1, 3, 4, 5)}
    assert [evals[n]["overall_score"] for n in (1, 3, 4, 5)] == [8.8, 2.0, 6.8, 6.8]

    response = client.get(f"/api/interviews/{session_id}/results")
    assert response.status_code == 200
    result = response.json()

    scores = {q["number"]: q["score"] for q in result["questions"]}
    assert scores == {1: 8.8, 2: 0, 3: 2.0, 4: 6.8, 5: 6.8}
    assert result["overall_score"] == round(sum(scores.values()) / 5 * 10) == 49  # (8.8+0+2+6.8+6.8)/5*10 = 49.2
    assert result["performance_label"] == "Average"
    assert (result["answered_count"], result["skipped_count"]) == (4, 1)
    # per criterion over all 5 questions (the skipped one counts as 0): accuracy (9+0+2+7+7)/5, relevance (9+0+3+8+8)/5, ...
    assert result["criteria_averages"] == {"technical_accuracy": 5.0, "relevance": 5.6, "clarity": 4.4, "completeness": 4.4}
    assert [q["text"] for q in result["questions"]] == [q["text"] for q in start["questions"]]
    assert result["questions"][1]["status"] == "skipped" and result["questions"][1]["evaluation"] is None

    # Report text comes from Gemini's per-answer feedback, not from canned wording
    assert result["strengths"] == ["(stub) Stayed on topic."]  # first strength of the answers (identical across the stub's replies)
    assert result["weaknesses"][0] == "Skipped 1 question."
    assert "(stub) Explain the trade-offs." in result["weaknesses"]
    assert "Study (stub) Core concepts for this role." in result["learning_recommendations"]
    assert any(r.startswith("Revisit the skipped question on") for r in result["learning_recommendations"])
    assert 3 <= len(result["learning_recommendations"]) <= 5

    # Strongest / weakest skill: the real highest and lowest criterion averages (relevance 5.6 vs clarity and completeness 4.4)
    assert (result["strongest_skill"], result["weakest_skill"]) == ("relevance", "clarity")

    # A concise summary written by Gemini from the stored evaluations (1 question generation + 4 evaluations + 1 summary)
    assert result["summary"] == "(stub) You scored 49/100 overall. Focus on the improvement areas in your feedback and revisit the recommended topics before you retake the interview."
    assert result["summary_error"] is None
    assert len(gemini.requests) == 6 and len(summary_requests(gemini)) == 1


